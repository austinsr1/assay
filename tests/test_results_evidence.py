"""The committed test evidence must describe the suite that actually runs.

`docs/results/latest.md` is generated by `tools/record-results.sh` and committed,
so a reviewer can see what passed without running anything. That is only useful
if it cannot silently go stale, so this module asserts the recorded totals match
the suite as currently collected.

Adding a test without re-recording fails here. That is the point.
"""

from __future__ import annotations

import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "docs" / "results"
LATEST = RESULTS / "latest.md"
JUNIT = RESULTS / "junit.xml"


def _in_git_checkout() -> bool:
    """Whether this working copy carries a ``.git`` directory.

    An external review bundle deliberately does not: including ``.git`` would
    publish the full history of the internal-only files that the bundle excludes.
    The repository-integrity checks below are about the repository, not the code,
    so they skip in a bundle rather than failing. In a real checkout they always
    run - the repo suite has no skips.
    """
    return (REPO / ".git").exists()


requires_repo = pytest.mark.skipif(
    not _in_git_checkout(),
    reason="not a git checkout: this is an external review bundle, from which "
           ".git and the internal-only files are deliberately excluded",
)


def _recorded_field(name: str) -> str:
    text = LATEST.read_text(encoding="utf-8")
    m = re.search(rf"^\| {re.escape(name)} \| (.+?) \|$", text, re.MULTILINE)
    assert m, f"could not find field {name!r} in {LATEST}"
    return m.group(1).strip().strip("`")


def _junit_totals() -> tuple[int, int, int]:
    """Return (tests, failures, errors) from the committed junit XML."""
    root = ET.parse(JUNIT).getroot()
    suites = root.findall("testsuite") or [root]
    tests = failures = errors = 0
    for s in suites:
        tests += int(s.get("tests", 0))
        failures += int(s.get("failures", 0))
        errors += int(s.get("errors", 0))
    return tests, failures, errors


def _collected_count() -> int:
    """Number of tests the suite currently collects.

    ``-o addopts=`` clears the project's ``addopts = "-q"``. Without it, the
    extra ``-q`` here stacks into double-quiet, which suppresses the
    "N tests collected" summary and prints a per-file breakdown instead.
    Counting ``::`` lines is kept as a fallback so this cannot silently return a
    wrong number if pytest changes its output format again.
    """
    out = subprocess.run(
        ["python3", "-m", "pytest", "tests/", "--collect-only", "-q",
         "-o", "addopts="],
        cwd=REPO, capture_output=True, text=True,
    )
    m = re.search(r"(\d+) tests? collected", out.stdout)
    if m:
        return int(m.group(1))
    nodeids = {ln for ln in out.stdout.splitlines() if "::" in ln}
    assert nodeids, f"could not determine collected count:\n{out.stdout[-500:]}"
    return len(nodeids)


def test_evidence_artifacts_exist():
    assert LATEST.is_file(), (
        "docs/results/latest.md is missing - run tools/record-results.sh"
    )
    assert JUNIT.is_file(), (
        "docs/results/junit.xml is missing - run tools/record-results.sh"
    )


def test_recorded_totals_match_the_suite():
    """The committed evidence must describe the suite that actually runs.

    This is the staleness guard. Adding or removing a test without re-recording
    makes the recorded total diverge from the collected total and fails here.
    It converges after one regeneration, unlike a pass/fail assertion would.
    """
    recorded = int(_recorded_field("Collected"))
    collected = _collected_count()
    assert recorded == collected, (
        f"docs/results/latest.md records {recorded} tests but the suite now "
        f"collects {collected}. Re-run tools/record-results.sh and commit."
    )


def test_committed_evidence_is_internally_consistent():
    """The recorded counts must agree with each other and with junit.xml.

    Note what is deliberately *not* asserted here: that the recorded run passed.
    A test asserting that would read the previous run's artifact, so a bootstrap
    failure would never converge -- each run would record the prior run's
    failures and fail again forever. Enforcement that red evidence is not
    committed lives in `tools/record-results.sh`, which exits non-zero and warns
    loudly when the suite fails.
    """
    collected = int(_recorded_field("Collected"))
    passed = int(_recorded_field("Passed"))
    failed = int(_recorded_field("Failed"))
    skipped = int(_recorded_field("Skipped"))
    # An xfail ran and failed as declared; a skip did not run. junit reports both
    # under a `skipped` element and distinguishes them only by type, so the
    # artifact records them separately and the arithmetic has to include both.
    xfailed = int(_recorded_field("Expected failures (xfail)"))
    assert passed + failed + skipped + xfailed == collected, (
        f"recorded counts disagree: {passed} passed + {failed} failed + "
        f"{skipped} skipped + {xfailed} xfailed != {collected} collected"
    )

    j_tests, j_failures, j_errors = _junit_totals()
    assert j_tests == collected, (
        f"junit.xml records {j_tests} tests but latest.md records {collected}. "
        f"Re-run tools/record-results.sh and commit both files together."
    )
    assert j_failures + j_errors == failed, (
        f"junit.xml reports {j_failures} failures and {j_errors} errors but "
        f"latest.md records {failed} failed. The two artifacts are from "
        f"different runs."
    )


@requires_repo
def test_recorded_commit_is_real_and_described():
    sha = _recorded_field("Describes commit")
    assert re.fullmatch(r"[0-9a-f]{7,40}|unknown", sha), f"bad commit sha: {sha!r}"
    if sha == "unknown":
        pytest.skip("results were recorded outside a git checkout")
    resolved = subprocess.run(
        ["git", "cat-file", "-e", f"{sha}^{{commit}}"],
        cwd=REPO, capture_output=True,
    )
    assert resolved.returncode == 0, (
        f"docs/results/latest.md names commit {sha}, which does not exist in "
        f"this repository. The evidence is not tied to real code."
    )


def test_evidence_leaks_no_host_identity():
    """This artifact is committed to a public repository."""
    text = LATEST.read_text(encoding="utf-8").lower()
    for forbidden in (
        "hostname", "node()", "/home/", "/users/", "192.168.", "10.9.0.",
        "austinsr", "agent@",
    ):
        assert forbidden not in text, (
            f"docs/results/latest.md contains host-identifying string "
            f"{forbidden!r}; record-results.sh must not emit it"
        )
